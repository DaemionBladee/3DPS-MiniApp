"""Credential-free, network-free worker entry point; emits only a bounded JSON result."""

import hashlib
import json
import math
import re
import signal
import subprocess
import sys
import zipfile
from pathlib import Path
from typing import TYPE_CHECKING, Any
from xml.etree import ElementTree as ET

sys.path.insert(0, "/opt")
from worker.geometry import GeometryError, analyze, geometric_signature, load, write_stl
from worker.limits import apply, probe, require_sandbox

if TYPE_CHECKING:
    from app.analysis.profile_config import (
        ENGINE_VERSION,
        canonical_hash,
        configuration,
        validate_profile,
    )
else:
    # Image build copies only the pure numeric configuration module here.
    from worker.profiles import ENGINE_VERSION, canonical_hash, configuration, validate_profile
from worker.structural import InvalidModel, inspect  # type: ignore[import-not-found]

ENGINE = "/usr/bin/prusa-slicer"
ANALYZER_VERSION = "3dps-geometry-1"
MAX_OUTPUT_BYTES = 64 * 1024**2


def digest(path: Path) -> str:
    checksum = hashlib.sha256()
    with path.open("rb") as source:
        while data := source.read(65536):
            checksum.update(data)
    return checksum.hexdigest()


def run_engine(arguments: list[str], label: str, timeout: int = 45) -> str:
    target = Path("/work") / (label + ".log")
    with target.open("wb") as output:
        process = subprocess.run(
            [ENGINE, *arguments],
            stdin=subprocess.DEVNULL,
            stdout=output,
            stderr=subprocess.STDOUT,
            timeout=timeout,
            check=False,
            env={
                "PATH": "/usr/bin:/bin",
                "LANG": "C.UTF-8",
                "HOME": "/work/home",
                "XDG_CONFIG_HOME": "/work/home",
            },
            close_fds=True,
        )
    if target.stat().st_size > 1024 * 1024:
        raise GeometryError("slicer_log_limit")
    text = target.read_text(encoding="utf-8", errors="replace")
    if process.returncode != 0:
        raise GeometryError("slicer_failed")
    return text


def parse_output(path: Path) -> dict[str, Any]:
    if not path.is_file() or not 0 < path.stat().st_size <= MAX_OUTPUT_BYTES:
        raise GeometryError("slicer_partial_output")
    grams = None
    seconds = None
    generated = False
    motion = 0
    canonical = hashlib.sha256()
    with path.open("rb") as source:
        for raw in source:
            if len(raw) > 16384:
                raise GeometryError("invalid_slicer_output")
            line = raw.decode("ascii", errors="strict").strip()
            if line.startswith(
                "; generated by PrusaSlicer " + ENGINE_VERSION.split("+", 1)[0] + " on "
            ):
                generated = True
            else:
                canonical.update(raw)
            if line.startswith("G1 ") and "E" in line:
                motion += 1
            match = re.fullmatch(r"; filament used \[g\] = ([0-9]+(?:\.[0-9]+)?)", line)
            if match:
                if grams is not None:
                    raise GeometryError("invalid_slicer_output")
                grams = float(match[1])
            match = re.fullmatch(
                r"; estimated printing time \(normal mode\) = (.+)", line
            )
            if match:
                if seconds is not None:
                    raise GeometryError("invalid_slicer_output")
                value = match[1]
                parts = re.findall(r"([0-9]+)([dhms])", value)
                if not parts or re.sub(r"([0-9]+)([dhms])", "", value).strip():
                    raise GeometryError("invalid_slicer_output")
                seconds = sum(
                    int(number) * {"d": 86400, "h": 3600, "m": 60, "s": 1}[unit]
                    for number, unit in parts
                )
    if (
        not generated
        or not motion
        or grams is None
        or seconds is None
        or not math.isfinite(grams)
        or not 0 < grams <= 1_000_000
        or not 0 < seconds <= 31_536_000
    ):
        raise GeometryError("slicer_partial_output")
    return {
        "filament_g": grams,
        "print_seconds": seconds,
        "support_g": None,
        "support_estimate_available": False,
        "gcode_sha256": digest(path),
        "canonical_gcode_sha256": canonical.hexdigest(),
        "gcode_bytes": path.stat().st_size,
    }


def process() -> dict[str, Any]:
    sandbox = require_sandbox()
    manifest_path = Path("/input/job.json")
    if manifest_path.stat().st_size > 32768:
        raise GeometryError("invalid_manifest")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if (
        set(manifest)
        != {
            "schema_version",
            "task_id",
            "lease_token",
            "input_sha256",
            "input_format",
            "profile_sha256",
            "profile",
            "specification",
        }
        or manifest["schema_version"] != 1
    ):
        raise GeometryError("invalid_manifest")
    version_text = run_engine(["--help"], "version", timeout=10)
    if f"PrusaSlicer-{ENGINE_VERSION} based on Slic3r" not in version_text:
        raise GeometryError("slicer_version_mismatch")
    profile = validate_profile(manifest["profile"])
    if canonical_hash(profile) != manifest["profile_sha256"]:
        raise GeometryError("unsafe_profile")
    source = Path("/input/model.bin")
    if (
        not 0 < source.stat().st_size <= 100 * 1024**2
        or digest(source) != manifest["input_sha256"]
    ):
        raise GeometryError("input_checksum_mismatch")
    with source.open("rb") as handle:
        inspected = inspect(
            handle,
            source.stat().st_size,
            {
                "entries": 64,
                "expanded": 64 * 1024**2,
                "entry_bytes": 16 * 1024**2,
                "ratio": 100,
            },
        )
    if inspected["format"] != manifest["input_format"]:
        raise GeometryError("input_format_mismatch")
    geometry, triangles, review = analyze(
        source, inspected["format"], manifest["specification"], profile
    )
    result = {
        "schema_version": 1,
        "task_id": manifest["task_id"],
        "lease_token": manifest["lease_token"],
        "input_sha256": manifest["input_sha256"],
        "profile_sha256": manifest["profile_sha256"],
        "analyzer_version": ANALYZER_VERSION,
        "engine_version": ENGINE_VERSION,
        "executable_sha256": digest(Path(ENGINE)),
        "geometry": geometry,
        "outcome": "manual_review" if review else "estimated",
        "estimate": None,
        "sandbox": sandbox,
    }
    if review:
        return result
    Path("/work/home").mkdir()
    config = Path("/work/profile.ini")
    config.write_text(configuration(profile), encoding="ascii")
    model = Path("/work/model.stl")
    write_stl(model, triangles)
    # This CLI implicitly repairs while slicing. Probe its explicit repair first
    # and reject any topology/geometry change instead of silently adopting it.
    repaired = Path("/work/repair-check.stl")
    run_engine(
        [
            "--loglevel",
            "1",
            "--repair",
            "--export-stl",
            "--output",
            str(repaired),
            str(model),
        ],
        "repair",
    )
    checked, _, _, _ = load(repaired, "stl")
    if len(checked) != len(triangles) or geometric_signature(
        checked
    ) != geometric_signature(triangles):
        geometry["review_reasons"].append("slicer_repair_would_change_geometry")
        result["outcome"] = "manual_review"
        return result
    result["normalization_verified"] = True
    text = run_engine(
        [
            "--load",
            str(config),
            "--config-compatibility",
            "disable",
            "--loglevel",
            "1",
            "--center",
            f"{profile['build_x_mm'] / 2},{profile['build_y_mm'] / 2}",
            "--export-gcode",
            "--output",
            "/work/slice.gcode",
            str(model),
        ],
        "slice",
    )
    if any(
        word in text.lower()
        for word in ["warning", "repairing", "non-manifold", "error:"]
    ):
        geometry["warnings"].append("slicer_warning_requires_review")
    result["estimate"] = parse_output(Path("/work/slice.gcode"))
    return result


def timeout(_signum: int, _frame: Any) -> None:
    raise TimeoutError("worker_timeout")


def main() -> None:
    apply()
    signal.signal(signal.SIGALRM, timeout)
    signal.alarm(85)
    result: dict[str, Any]
    try:
        if len(sys.argv) == 2 and sys.argv[1].startswith("--probe="):
            result = {
                "probe": probe(sys.argv[1].split("=", 1)[1]),
                "engine_version": ENGINE_VERSION,
                "executable_sha256": digest(Path(ENGINE)),
            }
        elif len(sys.argv) > 1:
            raise GeometryError("invalid_arguments")
        else:
            result = process()
    except (TimeoutError, subprocess.TimeoutExpired):
        result = {"error": "worker_timeout", "retryable": True}
    except (
        GeometryError,
        InvalidModel,
        ValueError,
        KeyError,
        IndexError,
        AssertionError,
        UnicodeError,
        OverflowError,
        ET.ParseError,
        zipfile.BadZipFile,
    ) as error:
        code = (
            str(error)
            if isinstance(error, GeometryError)
            else getattr(error, "code", "malformed_geometry")
        )
        if not re.fullmatch(r"[a-z_]{3,80}", code):
            code = "malformed_geometry"
        result = {"error": code, "retryable": False}
    except MemoryError:
        result = {"error": "worker_memory_limit", "retryable": False}
    except OSError:
        result = {"error": "worker_io_limit", "retryable": False}
    encoded = json.dumps(result, sort_keys=True, separators=(",", ":"), allow_nan=False)
    if len(encoded.encode()) > 32768:
        encoded = '{"error":"worker_output_limit","retryable":false}'
    print(encoded, flush=True)


if __name__ == "__main__":
    main()
