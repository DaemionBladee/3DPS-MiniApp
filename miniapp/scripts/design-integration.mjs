/* global document, window */
import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import path from 'node:path'
import { expect } from '@playwright/test'

// Called by the existing loopback HTTPS harness. All APIs and DB writes are real.
export async function runDesignIntegration({ page, ownerPage, customer, owner, origin, frontend }) {
  await page.goto(`${origin}/app/requests/design`)
  await page.getByLabel('Design service', { exact: true }).selectOption('design_and_print')
  await page.getByRole('button', { name: 'Create design draft', exact: true }).click()
  await page.getByRole('heading', { name: 'Your design draft', exact: true }).waitFor()
  const designId = new URL(page.url()).pathname.split('/').at(-1)
  const description = `M05 browser bracket ${randomUUID()}`
  const autosave = page.waitForResponse(response => response.request().method() === 'PATCH' && response.url().endsWith(`/design-projects/${designId}/brief`))
  await page.getByLabel('Project description', { exact: true }).fill(description)
  await page.getByLabel('Intended use', { exact: true }).fill('Indoor demonstration bracket')
  await page.getByLabel('Dimensions or size requirements', { exact: true }).fill('30 x 20 x 10')
  await page.getByLabel('Tolerances or precision needs', { exact: true }).fill('Owner to advise')
  assert((await autosave).status() === 200, 'Design brief must autosave through real API.')
  await expect(page.getByRole('button', { name: '2. References', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '2. References', exact: true }).click()
  const referenceUpload = page.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('/design/files?'))
  await page.getByLabel('Choose a private reference').setInputFiles({ name: 'reference.txt', mimeType: 'text/plain', buffer: Buffer.from('M05 synthetic drawing notes: rounded edges.\n') })
  assert((await referenceUpload).status() === 201, 'Reference upload must use real private storage.')
  await page.reload()
  await page.getByRole('heading', { name: 'Your design draft', exact: true }).waitFor()
  await expect(page.getByLabel('Project description', { exact: true })).toHaveValue(description)
  await page.getByRole('button', { name: '3. Review', exact: true }).click()
  const submission = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/design-projects/${designId}/submit`))
  await page.getByRole('button', { name: 'Submit design brief', exact: true }).click()
  assert((await submission).status() === 200, 'Model-free design brief must submit successfully.')
  await page.getByRole('heading', { name: 'Design request details', exact: true }).waitFor()
  console.log('PASS M05 1/4: persisted combined design brief, private reference upload, autosave and reload without STL/print items.')

  await ownerPage.goto(`${origin}/owner`)
  await ownerPage.getByRole('button', { name: 'Load design reviews', exact: true }).click()
  await ownerPage.getByRole('link', { name: `Open design ${designId.slice(0,8)}`, exact: true }).click()
  await ownerPage.getByLabel('Agreed deliverables proposal', { exact: true }).fill('One proof and a manufacturing model, no digital source-file transfer.')
  await ownerPage.getByLabel('Permitted revisions after first proof', { exact: true }).fill('1')
  await ownerPage.getByLabel('Exclusions', { exact: true }).fill('No live production or digital release.')
  await ownerPage.getByLabel('Reason for scope proposal', { exact: true }).fill('M05 simulation scope review')
  const proposal = ownerPage.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/design-projects/${designId}/scopes`))
  await ownerPage.getByRole('button', { name: 'Propose simulation scope', exact: true }).click()
  assert((await proposal).status() === 200, 'Owner scope proposal must be versioned and audited.')
  await page.reload()
  await page.getByRole('button', { name: 'Agree to simulation scope 1', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Agree to simulation scope 1', exact: true })).toHaveCount(0)
  await ownerPage.reload()
  await ownerPage.getByLabel('I confirm this is a simulation with no real funds').check()
  const fixture = ownerPage.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/design-projects/${designId}/simulation-fixture`))
  await ownerPage.getByRole('button', { name: 'Start simulation-paid fixture', exact: true }).click()
  assert((await fixture).status() === 200, 'Only explicit Owner simulation fixture authorizes simulated proof work.')
  console.log('PASS M05 2/4: Owner proposal, exact-scope customer agreement and explicit simulation-paid fixture; no live financial action.')

  const proofUpload = ownerPage.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('purpose=design_proof'))
  await ownerPage.getByLabel('Choose a review proof').setInputFiles({ name: 'proof.txt', mimeType: 'text/plain', buffer: Buffer.from('Bracket proof version 1: intended shape and rounded edges.\n') })
  const proofResponse = await proofUpload
  assert(proofResponse.status() === 201, 'Owner proof upload must finish validation.')
  const proofData = await proofResponse.json()
  const previewId = proofData.working_files.find(file => file.purpose === 'design_proof').id
  const modelUpload = ownerPage.waitForResponse(response => response.request().method() === 'POST' && response.url().includes('purpose=design_manufacturing'))
  const stl = Buffer.from('solid test\nfacet normal 0 0 1\nouter loop\nvertex 0 0 0\nvertex 1 0 0\nvertex 0 1 0\nendloop\nendfacet\nendsolid test\n')
  await expect(ownerPage.getByLabel('Choose a private manufacturing model')).toBeEnabled()
  await ownerPage.getByLabel('Choose a private manufacturing model').setInputFiles({ name: 'approved.stl', mimeType: 'application/octet-stream', buffer: stl })
  const modelResponse = await modelUpload
  assert(modelResponse.status() === 201, `Manufacturing upload must succeed (HTTP ${modelResponse.status()}).`)
  const modelData = await modelResponse.json()
  const modelId = modelData.working_files.find(file => file.purpose === 'design_manufacturing').id
  await expect(ownerPage.getByLabel('Review proof file', { exact: true })).toBeEnabled()
  await ownerPage.getByLabel('Review proof file', { exact: true }).selectOption(previewId)
  await ownerPage.getByLabel('Manufacturing-ready model (optional)', { exact: true }).selectOption(modelId)
  await ownerPage.getByLabel('Proof release notes', { exact: true }).fill('Simulation manufacturing proof version one')
  const publication = ownerPage.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/design-projects/${designId}/versions`))
  await ownerPage.getByRole('button', { name: 'Publish simulation proof', exact: true }).click()
  assert((await publication).status() === 200)
  await page.reload()
  await page.getByRole('button', { name: 'View proof proof.txt', exact: true }).click()
  await expect(page.getByText('Bracket proof version 1: intended shape and rounded edges.', { exact: true })).toBeVisible()
  assert((await customer.request.get(`${origin}/api/v1/files/${modelId}/download`)).status() === 404, 'Customer proof approval must not expose manufacturing source.')
  const review = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/design-projects/${designId}/reviews`))
  await page.getByRole('button', { name: 'Approve proof version 1', exact: true }).click()
  const reviewResponse = await review
  assert(reviewResponse.status() === 200)
  const approved = await reviewResponse.json()
  assert(approved.approved_version_id === approved.latest_version_id && approved.digital_release_available === false)
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile design details must not overflow.')
  await page.screenshot({ path: path.join(frontend, 'test-results/m05-customer-mobile.png'), fullPage: true })
  console.log('PASS M05 3/4: immutable proof publication, private viewer and exact-version approval preserve source-file privacy.')

  await ownerPage.reload()
  await ownerPage.getByRole('button', { name: 'Create linked printing draft', exact: true }).click()
  await ownerPage.getByRole('link', { name: 'Open linked printing request', exact: true }).waitFor()
  const attachment = ownerPage.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`/design-projects/${designId}/attach-print-model`))
  await ownerPage.getByRole('button', { name: 'Attach approved manufacturing model', exact: true }).click()
  const attachedResponse = await attachment
  assert(attachedResponse.status() === 200, 'Owner must attach exact approved model through M04 storage transactions.')
  const attached = await attachedResponse.json()
  const printing = attached.linked_print_request
  assert(printing.source_design_version_id === approved.approved_version_id && printing.status === 'draft')
  await ownerPage.screenshot({ path: path.join(frontend, 'test-results/m05-owner-desktop.png'), fullPage: true })
  await page.reload()
  await page.getByRole('link', { name: 'Open linked printing request', exact: true }).click()
  await page.getByRole('heading', { name: 'Your printing draft', exact: true }).waitFor()
  await expect(page.getByRole('button', { name: 'Download private model', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '2. Specifications', exact: true }).click()
  const item = page.getByRole('region', { name: 'Print item 1', exact: true })
  const configure = page.waitForResponse(response => response.request().method() === 'PATCH' && response.url().includes(`/requests/${printing.id}/items/`))
  await item.getByLabel('Material', { exact: true }).selectOption('dev-pla')
  await item.getByLabel('Color', { exact: true }).selectOption('dev-white')
  await item.getByLabel('Quality', { exact: true }).selectOption('dev-standard')
  await item.getByLabel('I confirm these are the model’s intended units').check()
  assert((await configure).status() === 200)
  await expect(page.getByRole('button', { name: '4. Review', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '4. Review', exact: true }).click()
  await page.getByRole('button', { name: 'Submit printing request', exact: true }).click()
  await page.getByRole('heading', { name: 'Pending analysis', exact: true }).waitFor()
  const unchanged = await (await owner.request.get(`${origin}/api/v1/design-projects/${designId}`)).json()
  assert(unchanged.state === 'approved' && unchanged.request.status === 'submitted' && unchanged.linked_print_request.status === 'submitted', 'Design and printing states remain independent.')
  assert((await page.evaluate(() => Object.keys(localStorage))).length === 0)
  console.log('PASS M05 4/4: approved-version lineage, private model attachment, independent print specifications/submission and pending analysis.')
}
