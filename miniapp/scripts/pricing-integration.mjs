import assert from 'node:assert/strict'
import { expect } from '@playwright/test'

export async function runPricingIntegration({ page, ownerPage, customer, owner, origin, printingId }) {
  const designUrl = ownerPage.url()
  assert(designUrl.includes('/owner/designs/'), 'M05 must leave the Owner inspecting the combined design.')
  await ownerPage.goto(`${origin}/owner`)
  await ownerPage.getByRole('button', { name: 'Load pricing workspace', exact: true }).click()
  async function publish(stage) {
    await ownerPage.getByLabel('Pricing stage', { exact: true }).selectOption(stage)
    await ownerPage.getByRole('button', { name: 'Load hypothetical policy template', exact: true }).click()
    await expect(ownerPage.getByLabel('Simulation policy JSON', { exact: true })).toHaveValue(new RegExp(`"stage_kind": "${stage}"`))
    await ownerPage.getByLabel('Configuration review reason', { exact: true }).fill('Explicit hypothetical browser-test configuration')
    const response = ownerPage.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/owner/pricing/policies'))
    await ownerPage.getByRole('button', { name: 'Publish simulation policy version', exact: true }).click()
    assert.equal((await response).status(), 201)
    await expect(ownerPage.getByRole('button', { name: 'Publish simulation policy version', exact: true })).toBeEnabled()
  }
  await publish('printing')
  await publish('design')
  await ownerPage.goto(designUrl)
  await ownerPage.getByLabel('Estimated design hours', { exact: true }).fill('1.5')
  await ownerPage.getByLabel('Hours per included revision', { exact: true }).fill('0.5')
  await ownerPage.getByLabel('Usage rights basis', { exact: true }).selectOption('commercial')
  const calculation = ownerPage.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/estimates'))
  await ownerPage.getByRole('button', { name: 'Calculate test estimate', exact: true }).click()
  assert.equal((await calculation).status(), 201)
  await expect(ownerPage.getByText('Estimated total: 110.00000000 XTR', { exact: true })).toBeVisible()
  await ownerPage.getByText('Owner cost breakdown and eligibility', { exact: true }).click()
  await expect(ownerPage.getByRole('table', { name: 'Private cost components', exact: true })).toBeVisible()
  await page.goto(designUrl.replace('/owner/designs/', '/app/design-projects/'))
  await expect(page.getByText('Estimated total: 110.00000000 XTR', { exact: true })).toBeVisible()
  assert.equal(await page.getByText('Owner cost breakdown and eligibility', { exact: true }).count(), 0)
  assert.equal(await page.getByRole('button', { name: /accept quote|pay now/i }).count(), 0)
  const configuration = await customer.request.get(`${origin}/api/v1/owner/pricing/configuration`)
  assert.equal(configuration.status(), 403)
  await page.reload()
  await expect(page.getByText('Estimated total: 110.00000000 XTR', { exact: true })).toBeVisible()
  console.log('PASS M07 1/2: Owner policy UI, scoped XTR calculation, private cost breakdown and Customer reload through real HTTPS/API/PostgreSQL.')

  await page.goto(`${origin}/app/requests/${printingId}`)
  const printCalculation = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/estimates'))
  await page.getByRole('button', { name: 'Calculate test estimate', exact: true }).click()
  assert.equal((await printCalculation).status(), 201)
  await expect(page.getByText('Current price unavailable — review or refresh required.', { exact: true })).toBeVisible()
  const result = await (await customer.request.get(`${origin}/api/v1/requests/${printingId}/estimates`)).json()
  assert.equal(result.estimate.currency_code, 'MMK')
  assert.equal(result.estimate.estimated_total, null, 'Incomplete model analysis must not create a false complete price.')
  assert.equal(result.estimate.acceptable, false)
  const privateResult = await (await owner.request.get(`${origin}/api/v1/owner/requests/${printingId}/estimates`)).json()
  assert(privateResult.estimate.lines.length > 0 && privateResult.estimate.unknown_costs.length > 0)
  assert.equal(await page.evaluate(() => Object.keys(localStorage).length), 0)
  console.log('PASS M07 2/2: printing MMK remains independent, missing native metrics fail closed, no acceptance/payment or browser-stored pricing data.')
}
